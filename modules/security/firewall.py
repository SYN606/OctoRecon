    async def run(self, scanner: 'Scanner') -> ModuleResult:
        result = ModuleResult(module_name=self.name, max_score=self.max_score)
        
        detected_wafs: Dict[str, List[str]] = {}
        
        # 1. Passive Analysis of Initial Response
        if scanner.response:
            self._analyze_response(scanner.response, detected_wafs, "Passive Baseline Response")

        # 2. Active Probe (Safe non-destructive probe to check active WAF inspection)
        try:
            probe_url = urljoin(scanner.target, "/?octorecon_waf_probe=<script>alert(1)</script>&x=../etc/passwd")
            probe_response = await scanner.client.get(probe_url)
            
            # Check if server blocked the probe (403 Forbidden, 406 Not Acceptable, 501, 999)
            if probe_response.status_code in [403, 406, 429, 501, 999]:
                self._analyze_response(probe_response, detected_wafs, f"Active Trigger Probe (HTTP {probe_response.status_code})")
                
                # If status is blocked but no specific vendor name found, note generic block
                if not detected_wafs:
                    detected_wafs["Generic WAF / Filter"] = [f"Blocked malicious payload with HTTP {probe_response.status_code}"]
        except Exception:
            # Active probe failure is ignored gracefully
            pass

        # 3. Format Results
        if detected_wafs:
            result.score = self.max_score # Having a WAF is strong security posture
            waf_names = list(detected_wafs.keys())
            primary_waf = waf_names[0]
            
            result.description = f"Active protection detected! Target is shielded by {', '.join(waf_names)}."
            
            result.data.append({"Property": "Protection Status", "Value": "Protected (WAF Detected)"})
            result.data.append({"Property": "Identified WAF", "Value": ", ".join(waf_names)})
            
            for waf, evidences in detected_wafs.items():
                for evidence in evidences:
                    result.data.append({"Property": f"{waf} Evidence", "Value": evidence})
        else:
            result.score = 5 # Penalty: No WAF detected leaves target exposed to direct web exploits
            result.description = "No Web Application Firewall (WAF) or DDoS protection detected. Application may be exposed directly."
            result.data.append({"Property": "Protection Status", "Value": "Unprotected / No WAF Detected"})
            result.data.append({"Property": "Recommendation", "Value": "Deploy a Cloud WAF (e.g. Cloudflare, AWS WAF, Fastly) to filter automated attacks and OWASP Top 10 exploits."})

        return result

    def _analyze_response(self, response, detected_wafs: Dict[str, List[str]], context: str):
        headers_lower = {k.lower(): v.lower() for k, v in response.headers.items()}
        server_header = headers_lower.get("server", "")
        cookies_header = headers_lower.get("set-cookie", "")
        body_sample = response.text[:15000].lower() if hasattr(response, "text") and response.text else ""

        for waf_name, sigs in self.WAF_SIGNATURES.items():
            # Check Headers
            for h in sigs.get("headers", []):
                if h in headers_lower:
                    detected_wafs.setdefault(waf_name, []).append(f"Header: '{h}' in {context}")

            # Check Server Header
            for s in sigs.get("server", []):
                if s in server_header:
                    detected_wafs.setdefault(waf_name, []).append(f"Server Token: '{server_header}' in {context}")

            # Check Cookies (match cookie name with boundary or regex)
            for c in sigs.get("cookies", []):
                pattern = rf"(?:^|[\s;,]){c}(?:[=\s;]|$)"
                if re.search(pattern, cookies_header, re.IGNORECASE):
                    detected_wafs.setdefault(waf_name, []).append(f"Cookie: '{c}' in {context}")

            # Check Body
            for b in sigs.get("body", []):
                if b in body_sample:
                    detected_wafs.setdefault(waf_name, []).append(f"Block Signature in body: '{b}' ({context})")
